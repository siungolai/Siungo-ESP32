#pragma once

// 电池电压采样。
//
// 板上的分压是 VBAT -- R21 200K --+-- R23 100K -- GND，采样点接 GPIO4
// （ADC1_CH3）。所以引脚电压是电池电压的 1/3，还原时乘 3。
//
// 官方给的是 12 bit、12 dB 衰减，再套 IDF 的曲线拟合校准。注意 12 dB 档
// 在 ESP32-S3 上量程约 0–3.1 V，按 1/3 分压反推，电池最高可测约 9 V，
// 4.2 V 的锂电远在量程内，不需要再改衰减。
//
// 这个文件只负责「把电压量准」；「电压怎么映射成百分比」也在这一层做，
// 因为换算法是这块板的物理事实，不是界面的职责。

#include <stdint.h>

namespace battery {

struct Sample {
  bool ok = false;
  int raw = 0;        // ADC 原始码，0–4095
  int pinMv = 0;      // 校准后的引脚电压，毫伏
  float packV = 0;    // 还原后的电池电压，伏
  int pct = 0;        // 0–100
};

bool begin();
bool ready();

// 读一次并做多次采样平均。
//
// 单次 ADC 读数在这里能跳几十毫伏（上面并着两颗 100 nF 也没压住开关电源的
// 纹波），不平均的话页首电池图标会一格一格地闪。
bool read(Sample *out);

// 电压到百分比的映射，与官方例程一致：
//   < 3.00 V -> 0
//   > 4.12 V -> 100
//   之间线性：(v - 3.0) / 1.12 * 100
//
// 这是一条工程化的曲线，不是锂电真实放电曲线 —— 满电到 3.9 V 之间掉得很快、
// 中段很平、接近 3.6 V 才开始陡降。做成线性是为了「数字不跳」，不是为了准确。
int percentFromVolts(float v);

}  // namespace battery
