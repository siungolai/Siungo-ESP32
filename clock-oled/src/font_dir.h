/**
 * font_dir.h —— 「字模纵向方向」的运行时自检
 *
 * ────────────────────────────────────────────────────────────────────
 * 为什么需要它
 * ────────────────────────────────────────────────────────────────────
 * uptime-oled / clock-oled 都把字模取模方向定为
 * 「1 字节 = 1 列，bit0 = 页内最上一行」，并把上下翻转写死成
 * `cmd(CMD_COM_SCAN_DEC)  // 0xC8`。
 *
 * 这两处互相独立：字模方向是你怎么存数据，COM 扫描是屏幕怎么扫。
 * 一旦不匹配，同一套字库就显示成上下镜像，而**编译不报错、串口日志正常**——
 * 正是最难查的那类问题。所以在烧下一套固件前，让屏幕自己回答。
 *
 * ────────────────────────────────────────────────────────────────────
 * 看屏判读（画面上只有两条同长的 1x4 竖条，相隔 14 行）
 * ────────────────────────────────────────────────────────────────────
 *   一条贴左缘（x=2），一条贴右缘（x=120），互不构成镜像，
 *   所以只看一条事实：**哪条竖条离屏幕垂直中心更远**。
 *
 *     更靠外的那条在上  ->  0xC8 正确，字模保持 bit0 = 上
 *     更靠外的那条在下  ->  0xC8 反了，改用 CMD_COM_SCAN_NORMAL (0xC0)，
 *                          或把字模纵向翻转
 *
 * 只回答这一个是非题，别在脑子里同时推两件事。
 *
 * ⚠️ 本文件只被一处使用：`tools/font-dir-probe/`。它存在的唯一理由是让
 *    探针和驱动文档共用同一份判据，避免两处各写一遍、改一处忘另一处。
 */
